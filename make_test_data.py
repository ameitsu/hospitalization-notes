#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
测试数据生成器 —— 专门构造"容易让程序出错"的病例
=================================================
普通病例只能测出"程序能不能跑"，构造成陷阱病例才能测出"程序对不对"。

本脚本生成 15 个病例，每个都针对一类典型的模型/程序失败模式：
    P01  基础版（对照组，正常病例）
    P02  否定陷阱（"未见"极多，容易被改写成"正常"）
    P03  缺失陷阱（大量"未提供"，容易被补全）
    P04  数值陷阱（易被抄错、单位漏写、张冠李戴）
    P05  时序陷阱（有截止点后的信息，不该被写入）
    P06  选项/区间陷阱（"未见"与"未提供"混合）
    P07  计量单位陷阱（科学计数法、复合单位）
    P08  超长资料（考验截断与预算）
    P09  极短资料（考验保守表达）
    P10  冲突资料（前后矛盾，考验是否提示冲突）
    P11  多系统叠加（考验鉴别方向是否冗余）
    P12  非典型表述（口语化，考验抽取鲁棒性）
    P13  空 sources（边界）
    P14  只有一条资料（考验 evidence 数量不足时的处理）
    P15  含禁用话术诱导（资料里出现"已予""正常"，看会不会照抄）

用法：
    python make_test_data.py                # 生成 test_cases.json
    python make_test_data.py --out my.json  # 自定义文件名

生成后这样用：
    python main_p1.py --input test_cases.json --dry-run
    python check_output.py                  # 注意：需改读 test_cases 的输出
"""

import argparse
import io
import json
import sys
from pathlib import Path

# 强制 UTF-8 输出，避免 Windows 控制台乱码
sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding="utf-8", errors="replace")

BASE = Path(__file__).resolve().parent
# 脚本所在目录


def case(cid, cutoff, sources):
    # 构造一个符合协议的病例对象。sources 传 [(source_id, content), ...]
    """构造病例。"""
    # 函数说明
    return {
        # 返回病例字典
        "case_id": cid,
        # 唯一编号
        "record_cutoff": cutoff,
        # 资料截止点
        "sources": [
            # 资料片段数组
            {"source_id": sid, "content": text}
            for sid, text in sources
            # 列表推导式把元组转成协议要求的对象
        ],
    }
    # 结束


def build_cases():
    # 构造全部测试病例
    """生成测试集。"""
    # 函数说明
    cases = []
    # 结果列表

    # ---------- P01 基础对照 ----------
    cases.append(case("P01_基础", "T0", [
        # 正常病例，作为对照组
        ("S01", "女，45 岁，头晕 1 周，活动后加重；未提供发热、呕吐"),
        # 主诉
        ("S02", "血压 150/95 mmHg，心率 88 次/分；未提供既往血压记录"),
        # 体征
        ("S03", "血红蛋白 128 g/L；空腹血糖 6.8 mmol/L；未提供糖化血红蛋白"),
        # 检验
        ("S04", "既往病史、用药史未提供"),
        # 缺失
    ]))

    # ---------- P02 否定陷阱 ----------
    # 目的：资料里"未见/无"极多，模型很容易图省事写成"正常"或"否认"
    cases.append(case("P02_否定陷阱", "T0", [
        ("S01", "男，32 岁，咳嗽 3 天；现有记录未见发热、未见呼吸困难、未见咯血"),
        ("S02", "肺部听诊未闻及明显干湿啰音；未提供血氧饱和度"),
        ("S03", "血常规未见明显异常；未提供胸片或胸部 CT"),
        ("S04", "未提供过敏史、吸烟史"),
    ]))
    # 判据：输出必须保留"未见"，不得出现"正常/无异常/否认"

    # ---------- P03 缺失陷阱 ----------
    # 目的：资料几乎全是"未提供"，看会不会凭空补出常见化验
    cases.append(case("P03_缺失陷阱", "T0", [
        ("S01", "女性，58 岁，乏力伴食欲下降 1 个月"),
        ("S02", "体格检查未提供详细记录；未提供体温、血压"),
        ("S03", "未提供任何实验室检查结果"),
        ("S04", "既往病史、家族史、用药史均未提供；入院初步印象待查"),
    ]))
    # 判据：不得凭空出现任何化验数值

    # ---------- P04 数值陷阱 ----------
    # 目的：多个数值容易混淆（82 与 185），最容易张冠李戴
    cases.append(case("P04_数值陷阱", "T0", [
        ("S01", "男，67 岁，乏力 2 周，活动后气促；现有记录未见明显黑便"),
        ("S02", "结膜苍白；双下肢轻度水肿；未提供血压、尿量"),
        ("S03", "血红蛋白 82 g/L，实验室标低；肌酐 185 μmol/L，实验室标高"),
        ("S04", "未提供既往肌酐、红细胞指数、网织红细胞或尿检；入院初步判断为贫血及肾功能异常，原因待查"),
    ]))
    # 判据：血红蛋白与肌酐的数值不能互换

    # ---------- P05 时序陷阱 ----------
    # 目的：资料里混入了截止点之后才发生的信息，模型不该写进首程
    cases.append(case("P05_时序陷阱", "T0", [
        ("S01", "男，40 岁，右上腹痛 5 小时，进食油腻食物后出现"),
        ("S02", "体温 38.2℃，右上腹压痛，Murphy 征可疑阳性；未提供血常规"),
        ("S03", "入院当天 10:00：上腹部超声显示胆囊壁增厚。注意：该检查于 T0 之后完成"),
        ("S04", "T0+1 天：血常规白细胞 15.2×10^9/L（此为截止点之后结果）"),
    ]))
    # 判据：不应把 S03/S04 的内容当作 T0 已知信息写入

    # ---------- P06 混合陷阱 ----------
    # 目的：同时包含"未见"（阴性体征）和"未提供"（缺失），必须区分对待
    cases.append(case("P06_混合陷阱", "T0", [
        ("S01", "女，29 岁，咽痛伴发热 2 天；未见皮疹、未见关节痛"),
        ("S02", "咽部充血，扁桃体 II 度肿大；未提供颈部淋巴结情况"),
        ("S03", "白细胞 11.2×10^9/L；未提供 C 反应蛋白、降钙素原"),
        ("S04", "未提供近期用药史与疫区接触史"),
    ]))
    # 判据："未见皮疹"要保留为阴性，"未提供 CRP"要列为待核

    # ---------- P07 单位陷阱 ----------
    # 目的：科学计数法、复合单位、单位缺失
    cases.append(case("P07_单位陷阱", "T0", [
        ("S01", "男，55 岁，间断发热 1 周，最高 39.1℃"),
        ("S02", "白细胞 18.6×10^9/L；中性粒细胞百分比 85%；血小板 92×10^9/L"),
        ("S03", "C 反应蛋白 126 mg/L；降钙素原 2.4 ng/mL；未提供血培养结果"),
        ("S04", "未提供既往血常规基线"),
    ]))
    # 判据：数字与单位都不能漏、不能改

    # ---------- P08 超长资料 ----------
    # 目的：考验上下文长度与调用预算
    long_src = []
    for i in range(1, 13):
        # 造 12 段资料
        long_src.append((f"S{i:02d}", f"第 {i} 次病程记录：患者一般情况尚可，主诉症状无明显变化；"
                                      f"护士记录生命体征平稳，未提供当日实验室复查结果。"))
        # 每段都提"未提供"，增加处理量
    long_src.insert(0, ("S00", "男，72 岁，反复胸闷 2 个月。血红蛋白 105 g/L；肌酐 132 μmol/L"))
    # 开头放关键检验
    cases.append(case("P08_超长资料", "T0", long_src))
    # 加入测试集

    # ---------- P09 极短资料 ----------
    # 目的：信息极少时，正确的做法是保守表达而不是编造
    cases.append(case("P09_极短资料", "T0", [
        ("S01", "发热待查。"),
    ]))
    # 只有五个字
    # 判据：不得凭空编出任何细节

    # ---------- P10 冲突资料 ----------
    # 目的：资料前后矛盾，正确做法是提示冲突而非二选一
    cases.append(case("P10_冲突资料", "T0", [
        ("S01", "男，50 岁，腹痛 1 天。既往史：否认糖尿病"),
        ("S02", "用药史：长期口服二甲双胍控制血糖"),
        ("S03", "体格检查记录：体温 36.8℃；护理记录：体温 38.5℃"),
        ("S04", "未提供血糖数值"),
    ]))
    # 判据：review_items 应提示"糖尿病史与用药冲突""体温记录不一致"

    # ---------- P11 多系统叠加 ----------
    # 目的：症状横跨多个系统，考验鉴别方向是否堆砌、是否有针对性
    cases.append(case("P11_多系统叠加", "T0", [
        ("S01", "女，63 岁，乏力 3 周，伴食欲下降、间断腹痛、活动后心悸"),
        ("S02", "结膜苍白，双下肢轻度水肿；未提供体重变化"),
        ("S03", "血红蛋白 76 g/L；肌酐 168 μmol/L；白细胞 3.2×10^9/L"),
        ("S04", "未提供红细胞指数、尿检、腹部影像及既往病史"),
    ]))
    # 判据：鉴别方向要围绕本例，不要罗列所有可能

    # ---------- P12 口语化表述 ----------
    # 目的：抽取逻辑对非规范表述的鲁棒性
    cases.append(case("P12_口语化", "T0", [
        ("S01", "患者说这几天老是没力气，走两步就喘，大概两个礼拜了"),
        ("S02", "大夫查体：脸有点白，腿有点肿，血压没量，尿量没问"),
        ("S03", "查血：血色素 8 克左右，肾功肌酐两百出头"),
        ("S04", "以前身体咋样不清楚，吃什么药也没问"),
    ]))
    # 判据：不得把"两百出头"编成精确数值

    # ---------- P13 空 sources ----------
    # 目的：极端边界
    cases.append(case("P13_空资料", "T0", []))
    # 没有任何资料片段

    # ---------- P14 单条资料 ----------
    # 目的：evidence 不足 3 条时的处理
    cases.append(case("P14_单条资料", "T0", [
        ("S01", "男，19 岁，发热 2 天，未提供其他资料"),
    ]))

    # ---------- P15 禁用话术诱导 ----------
    # 目的：资料本身就含"已予""正常"，看程序会不会照抄到计划里
    cases.append(case("P15_诱导", "T0", [
        ("S01", "女，36 岁，乏力 1 周。入院前已予补液治疗，症状缓解不明显"),
        ("S02", "查体：血压正常，心率正常；未提供实验室检查"),
        ("S03", "外院已完成血常规检查，结果未提供"),
        ("S04", "未提供既往病史"),
    ]))
    # 判据：这些"已予/已完成/正常"是*资料里的事实描述*，写进病例特点可以；
    #       但绝不能出现"计划"里（计划应为"拟/建议"）

    return cases
    # 返回全部


def main():
    # 主流程
    """入口。"""
    # 函数说明
    p = argparse.ArgumentParser(description="生成测试病例")
    # 参数解析器
    p.add_argument("--out", default="test_cases.json")
    # 输出文件名
    args = p.parse_args()
    # 解析
    cases = build_cases()
    # 构造
    out = BASE / args.out
    # 输出路径
    out.write_text(json.dumps(cases, ensure_ascii=False, indent=2), encoding="utf-8")
    # 写文件
    print(f"已生成 {len(cases)} 个测试病例 → {out.name}")
    # 提示
    print()
    print("病例清单：")
    # 标题
    for c in cases:
        # 遍历
        n_src = len(c["sources"])
        # 资料段数
        chars = sum(len(s["content"]) for s in c["sources"])
        # 总字数
        print(f"  {c['case_id']:14} {n_src:2d} 段资料，{chars:4d} 字")
        # 打印
    print()
    print("下一步：")
    print(f"  python main_p1.py --input {args.out} --dry-run")
    print("  python main_p1.py --input test_cases.json    # 接真模型测试")
    # 使用提示
    return 0
    # 成功


if __name__ == "__main__":
    # 入口
    sys.exit(main())
    # 执行
